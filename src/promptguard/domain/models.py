from typing import Literal

from pydantic import BaseModel, Field

Difficulty = Literal["easy", "medium", "hard"]


class GoldenTestCase(BaseModel):
    id: str
    input: str

    expected_category: str
    ideal_summary: str

    expected_difficulty: Difficulty

    notes: str | None = None


class LLMOutput(BaseModel):
    """
    Structured output generated by the LLM.

    This contains only fields that the model is responsible
    for generating.
    """

    category: str = Field(
        min_length=1,
        description="The category assigned to the customer message.",
    )

    summary: str = Field(
        min_length=1,
        description="A concise summary of the customer message.",
    )


class LLMResponse(BaseModel):
    """
    Complete response returned by the LLM infrastructure layer.

    Combines the model-generated output with operational
    metadata captured by the client.
    """

    output: LLMOutput

    latency_ms: float = Field(ge=0)

    input_tokens: int = Field(ge=0)

    output_tokens: int = Field(ge=0)


class EvaluationResult(BaseModel):
    test_case_id: str

    expected_category: str
    actual_category: str

    expected_summary: str
    actual_summary: str

    category_match: bool

    summary_score: float = Field(
        ge=1,
        le=5,
    )

    latency_ms: float = Field(ge=0)

    input_tokens: int = Field(ge=0)
    output_tokens: int = Field(ge=0)