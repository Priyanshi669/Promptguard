"""State-aware models for the calibration draft workflow.

Three distinct statuses are modeled (see ADR-0002):
- ``draft_state``: mechanical readiness of the owner-prepared draft.
- ``validation_state``: categorized strict-validation findings
  (reviewer-pending blanks are expected on a draft; anything else is a
  defect).
- ``calibration_state``: whether the calibration workflow has actually
  been executed against real reviewer scores.

Nothing in this module writes or mutates calibration artifacts.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

DraftState = Literal[
    "missing",
    "prepared_final_draft",
]

ValidationState = Literal[
    "not_run",
    "error",
    "clean_draft_awaiting_reviewer_fields",
    "draft_with_defects",
]

CalibrationState = Literal[
    "not_executed",
    "executed_report_available",
]


class CandidateProvenance(BaseModel):
    """Provenance of the AI-generated candidate summary for one case."""

    candidate_model: str
    candidate_run_id: str
    candidate_generated_at: str
    candidate_status: str
    prompt_version: str


class DraftRow(BaseModel):
    """One annotated row of the owner-prepared workbook, read-only view.

    ``actual_summary`` is always AI-generated candidate text and must be
    labeled as such by consumers. ``provisional_reference`` is true when
    ``expected_summary`` exists but has no evidence of independent human
    validation (it may be a draft reference); it is never automatically
    claimed to be human-approved.
    """

    id: str
    annotation_pass: Literal["primary", "secondary"]
    is_double_annotated: bool
    source_split: str
    category: str
    source_category: str
    inclusion_status: str
    source_input: str
    expected_summary: str
    actual_summary: str
    actual_summary_is_ai_candidate: bool = Field(
        default=True,
        description=(
            "The candidate summary text is AI-generated by construction; "
            "exposed explicitly so the UI can label every row honestly."
        ),
    )
    provisional_reference: bool = Field(
        default=False,
        description=(
            "True when a reference draft exists but lacks evidence of "
            "independent human validation. A blank reference is simply "
            "pending reviewer input, not provisional."
        ),
    )
    reference_is_human_validated: bool = Field(
        default=False,
        description=(
            "True only when annotated evidence (annotator identity, "
            "timestamp) supports the reference. Blank reviewer fields "
            "keep this false."
        ),
    )
    human_score: str
    confidence: str
    notes: str
    annotator_id: str
    annotated_at: str
    candidate: CandidateProvenance | None = None


class DraftFinding(BaseModel):
    """One actionable finding from draft validation."""

    row_id: str
    field: str
    finding_type: Literal["pending_reviewer_field", "defect"]
    message: str
    hint: str | None = None


class StrictValidationSummary(BaseModel):
    """Strict validator output, categorized for the draft workflow.

    ``pending_reviewer_field_count`` errors are expected on a prepared
    draft awaiting human annotation. Any ``defect_count`` requires
    resolution before production-approved calibration runs.
    """

    validator: Literal["builtin", "scripts_validate_annotation_workbook"]
    status: str
    total_rows: int | None = None
    error_count: int
    pending_reviewer_field_count: int
    defect_count: int
    defects: list[DraftFinding] = Field(default_factory=list)
    raw_errors: list[str] = Field(default_factory=list)
    warning_count: int = 0


class DraftOverview(BaseModel):
    """Top-of-workspace state bundle for the calibration workspace."""

    draft_state: DraftState
    draft_version: str = "v1"
    total_rows: int
    unique_cases: int
    primary_rows: int
    secondary_rows: int
    scored_rows: int
    scored_unique_cases: int
    pending_reviewer_rows: int
    double_annotation_cases: int
    card_pin_provisional_cases: int
    candidate_run_ids: list[str]
    candidate_models: list[str]
    validation_state: ValidationState
    calibration_state: CalibrationState
    calibration_report_path: str | None = None
    strict_validation: StrictValidationSummary | None = None
    provenance_notes: list[str] = Field(default_factory=list)
